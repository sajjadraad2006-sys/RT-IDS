def get_all_scenarios() -> List[Dict[str, Any]]:
    """Return all 100+ attack scenarios with CLI helper snippets."""
    res = []
    for sc in ATTACK_VECTORS:
        item = dict(sc)
        item["curl_command"] = (
            f'curl -X POST http://127.0.0.1:8000/api/simulation/launch '
            f'-H "Content-Type: application/json" -d \'{{"scenario_id": "{sc["id"]}"}}\''
        )
        item["powershell_command"] = (
            f'Invoke-RestMethod -Uri "http://127.0.0.1:8000/api/simulation/launch" '
            f'-Method Post -ContentType "application/json" -Body \'{{"scenario_id": "{sc["id"]}"}}\''
        )
        res.append(item)
    return res


def get_scenarios_by_category(category: Optional[str] = None) -> List[Dict[str, Any]]:
    all_s = get_all_scenarios()
    if not category:
        return all_s
    return [s for s in all_s if s["category"].lower() == category.lower()]
